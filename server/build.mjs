/**
 * Headless build: produces a plain-Node bundle of Chat2API's main process plus a
 * static web UI, so the app can run on a phone (Termux) with no Electron at all.
 *
 * Steps
 *   1. Vite builds the React renderer  -> build/renderer/
 *   2. A renderer-only shim provides window.electronAPI over HTTP + SSE
 *   3. esbuild bundles src/main/index.ts -> headless/main.cjs (electron aliased)
 *
 * Usage: node server/build.mjs [--skip-renderer]
 */

import { build as viteBuild } from 'vite'
import { build as esbuild } from 'esbuild'
import react from '@vitejs/plugin-react'
import { fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outDir = path.join(root, 'headless-dist')
const rendererOut = path.join(outDir, 'renderer')
const skipRenderer = process.argv.includes('--skip-renderer')

const log = (msg) => console.log(`\x1b[36m[headless]\x1b[0m ${msg}`)

fs.mkdirSync(outDir, { recursive: true })

// ---------------------------------------------------------------------------
// 1 + 2. Renderer (React UI) with the browser IPC shim
// ---------------------------------------------------------------------------

if (!skipRenderer) {
  log('building renderer (vite)…')
  // The favicon lives with the desktop renderer; the server entry reuses it.
  fs.copyFileSync(
    path.join(root, 'src/renderer/favicon.png'),
    path.join(root, 'server/renderer/favicon.png')
  )

  // Root is server/renderer so Vite emits index.html at the web root rather
  // than mirroring the monorepo layout into the output directory.
  await viteBuild({
    root: path.join(root, 'server/renderer'),
    base: './',
    configFile: false,
    plugins: [react()],
    resolve: {
      alias: [
        { find: '@', replacement: path.join(root, 'src/renderer/src') },
        // Swap Electron's renderer-side module for the HTTP/SSE bridge. This is
        // what lets src/preload/index.ts run untouched in a browser.
        { find: /^electron$/, replacement: path.join(root, 'server/renderer/electron-shim.ts') },
      ],
    },
    build: {
      outDir: rendererOut,
      emptyOutDir: true,
      sourcemap: false,
      target: 'es2020',
      rollupOptions: {
        input: path.join(root, 'server/renderer/index.html'),
      },
    },
    logLevel: 'warn',
  })
  log(`renderer -> ${path.relative(root, rendererOut)}`)
}

// ---------------------------------------------------------------------------
// 3. Main process bundle
// ---------------------------------------------------------------------------

log('bundling main process (esbuild)…')

const shimPath = path.join(root, 'server/electron-shim.ts')
const updaterStub = path.join(root, 'server/stubs/electron-updater.ts')
const storeStub = path.join(root, 'server/stubs/electron-store.ts')

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

// Everything is bundled: the shipped artefact must run with `node main.cjs`
// alone (no node_modules), like 9router's app/server.js.
await esbuild({
  entryPoints: [path.join(root, 'server/main.ts')],
  outfile: path.join(outDir, 'main.cjs'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  sourcemap: false,
  minify: true,
  keepNames: false,
  logLevel: 'info',
  define: {
    'process.env.NODE_ENV': '"production"',
  },
  alias: {
    electron: shimPath,
    'electron-updater': updaterStub,
  },
  banner: {
    js: [
      '// Chat2API headless bundle — runs on plain Node (Termux/Android, CI, servers).',
      '// Generated by server/build.mjs. Do not edit.',
    ].join('\n'),
  },
  plugins: [
    {
      name: 'electron-store-node',
      setup(build) {
        // electron-store@10 needs Electron's `app`; point it at a Node-only store.
        build.onResolve({ filter: /^electron-store$/ }, () => ({ path: storeStub }))
      },
    },
  ],
})

log(`main -> ${path.relative(root, path.join(outDir, 'main.cjs'))}`)

// ---------------------------------------------------------------------------
// Ship the wasm the DeepSeek challenge solver reads at runtime
// ---------------------------------------------------------------------------

const wasmSrc = path.join(root, 'sha3_wasm_bg.7b9ca65ddd.wasm')
if (fs.existsSync(wasmSrc)) {
  fs.copyFileSync(wasmSrc, path.join(outDir, 'sha3_wasm_bg.7b9ca65ddd.wasm'))
  log('copied sha3 wasm')
}

// A package.json makes the folder installable/linkable via npm and pins type.
fs.writeFileSync(
  path.join(outDir, 'package.json'),
  JSON.stringify(
    {
      name: 'chat2api-headless',
      version: pkg.version,
      private: true,
      type: 'commonjs',
      main: 'main.cjs',
      bin: { 'chat2api-web': 'main.cjs' },
      scripts: {
        start: 'node main.cjs',
      },
    },
    null,
    2
  )
)

log('done')
